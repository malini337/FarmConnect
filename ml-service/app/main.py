from pathlib import Path
from datetime import date
import json
import joblib
import numpy as np
from fastapi import FastAPI, HTTPException
from app.schemas import PriceDemoRequest, DemandDemoRequest

ROOT = Path(__file__).resolve().parents[1]
MODEL_DIR = ROOT / "models"
app = FastAPI(title="FarmConnect ML Demo Service", version="0.1.0", description="Synthetic-data-only classroom demonstration; not validated for market use.")

def load_artifact(name):
    path = MODEL_DIR / name
    if not path.exists():
        return None
    try:
        return joblib.load(path)
    except Exception:
        return None

price_artifact = load_artifact("price_demo.joblib")
demand_artifact = load_artifact("demand_demo.joblib")

def category_id(category):
    values = {"vegetable": 0, "vegetables": 0, "fruit": 1, "fruits": 1, "grain": 2, "grains": 2, "pulse": 3, "pulses": 3, "spice": 4, "spices": 4, "flowers": 5, "flower": 5, "dairy products": 5, "seeds": 5, "oilseeds": 5, "nuts": 5, "honey": 5, "other": 5, "others": 5, "other agricultural products": 5}
    return values.get(category.strip().lower(), 5)

def product_id(artifact, product):
    mapping = artifact.get("product_to_id", {})
    return int(mapping.get(product.strip().lower(), mapping.get("tomato", 0)))

@app.get("/health")
def health():
    return {"status": "success", "service": "farmconnect-ml-demo", "model_status": {"price": "loaded" if price_artifact else "unavailable", "demand": "loaded" if demand_artifact else "unavailable"}}

@app.get("/models/status")
def model_status():
    def describe(a):
        if not a: return {"status": "model_unavailable"}
        return {"status": "success", "model_type": a["model_type"], "model_version": a["model_version"], "dataset_type": "synthetic_demo_only", "metrics": a["metrics"], "trained_at": a["trained_at"]}
    return {"price": describe(price_artifact), "demand": describe(demand_artifact)}

@app.post("/demo/price")
def price_demo(req: PriceDemoRequest):
    if not price_artifact:
        raise HTTPException(503, detail={"status":"model_unavailable", "message":"Train the synthetic demonstration model first."})
    row = np.array([[product_id(price_artifact, req.product), category_id(req.category), req.month, req.quantity_kg, req.quality_grade]], dtype=float)
    prediction = float(price_artifact["model"].predict(row)[0])
    return {"status":"success", "mode":"synthetic_demo_only", "is_real_market_price":False, "product":req.product, "category":req.category, "estimated_price_inr_per_kg":round(max(0.01,prediction),2), "prediction_date":date.today().isoformat(), "model_version":price_artifact["model_version"], "dataset_type":"synthetic", "data_coverage":"Generated classroom data; no real market records", "metrics":price_artifact["metrics"], "explanation":"This output is generated by a trained model fitted only on synthetic demonstration records. It is not a real market quote and must not be used for trading decisions."}

@app.post("/demo/demand")
def demand_demo(req: DemandDemoRequest):
    if not demand_artifact:
        raise HTTPException(503, detail={"status":"model_unavailable", "message":"Train the synthetic demonstration model first."})
    row = np.array([[product_id(demand_artifact, req.product), category_id(req.category), req.month, req.recent_monthly_quantity_kg]], dtype=float)
    prediction = float(demand_artifact["model"].predict(row)[0])
    return {"status":"success", "mode":"synthetic_demo_only", "is_real_demand":False, "product":req.product, "forecast_horizon_days":30, "estimated_quantity_kg":round(max(0,prediction),2), "prediction_date":date.today().isoformat(), "model_version":demand_artifact["model_version"], "dataset_type":"synthetic", "data_coverage":"Generated classroom data; no actual order history", "metrics":demand_artifact["metrics"], "explanation":"This is a synthetic-data demonstration forecast, not observed or validated market demand."}
