function normalize(value = "") {
  return String(value).trim().toLowerCase();
}

function parseReferences(raw) {
  try {
    const value = JSON.parse(raw || "[]");
    return Array.isArray(value) ? value : [];
  } catch {
    return [];
  }
}

function calculatePriceRecommendation({ name, category, location = "", unit = "kg", expectedPrice, references = [], language = "en" }) {
  const tamil = language === "ta";
  const expected = Number(expectedPrice);
  const validExpected = Number.isFinite(expected) && expected > 0 ? expected : null;
  const match = references.find((reference) => {
    const min = Number(reference.min);
    const max = Number(reference.max);
    return normalize(reference.name) === normalize(name)
      && normalize(reference.unit || "kg") === normalize(unit)
      && (!reference.category || normalize(reference.category) === normalize(category))
      && (!reference.location || normalize(reference.location) === normalize(location))
      && Number.isFinite(min) && Number.isFinite(max) && min > 0 && max >= min
      && typeof reference.source === "string" && reference.source.trim()
      && typeof reference.date === "string" && !Number.isNaN(Date.parse(reference.date));
  });

  if (!match) {
    return {
      status: "insufficient_data",
      expectedPrice: validExpected,
      suggestedRange: null,
      source: null,
      referenceDate: null,
      unit,
      location,
      explanation: tamil ? "இந்த விளைபொருள், இடம் மற்றும் அலகுக்கு பொருந்தும் தேதியிட்ட நம்பகமான விலைத் தரவு இல்லை. எனவே நியாயமான விலையை கணக்கிட முடியவில்லை; இறுதி விலையை விவசாயியே தீர்மானிக்கலாம்." : "No matching, dated and sourced reference price is configured for this produce, location and unit. A reliable recommendation cannot currently be calculated; the farmer retains control of the expected price.",
    };
  }
  return {
    status: "available",
    expectedPrice: validExpected,
    suggestedRange: { min: Number(match.min), max: Number(match.max) },
    source: match.source.trim(),
    referenceDate: match.date,
    unit,
    location: match.location || location,
    explanation: tamil ? `பரிந்துரைக்கப்பட்ட வரம்பு ${match.source} என்ற ஆதாரத்தில் ${match.date} தேதியிட்ட பதிவிலிருந்து பெறப்பட்டது; இது Gemini உருவாக்கிய விலை அல்ல. ஒரே அலகு மற்றும் உள்ளூர் நிலைமைகளுடன் ஒப்பிடவும்.` : `Range is taken from configured reference data (${match.source}, dated ${match.date}); it is not generated by Gemini. Compare like-for-like units and local conditions.`,
  };
}

module.exports = { calculatePriceRecommendation, parseReferences };
